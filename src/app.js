const express=require('express');
const helmet=require('helmet');
const cookieParser=require('cookie-parser');
const rateLimit=require('express-rate-limit');
const swaggerUi=require('swagger-ui-express');
const config=require('./config');
const auth=require('./middleware/auth');
const rbac=require('./middleware/rbac');
const errorHandler=require('./middleware/errorHandler');
const app=express();
app.use(helmet());app.use(express.json({limit:'10kb'}));app.use(cookieParser());
app.use('/auth/login',rateLimit({windowMs:15*60*1000,limit:10,standardHeaders:true,legacyHeaders:false}));
app.use('/auth',require('./routes/auth'));
app.get('/auth/me',auth,(req,res)=>res.json({status:'success',data:req.user}));
const swagger=require('./config/swagger');app.use('/api/docs',swaggerUi.serve,swaggerUi.setup(swagger));
app.use('/api/projects',auth,require('./routes/projects'));
app.use('/api/tasks',auth,require('./routes/tasks'));
app.get('/api/users',auth,rbac('ADMIN'),async(req,res,next)=>{try{res.json({status:'success',data:await config.prisma.user.findMany({select:{id:true,email:true,role:true,createdAt:true}})});}catch(e){next(e);}});
app.get('/health',async(req,res,next)=>{try{await config.prisma.$queryRaw`SELECT 1`;res.json({status:'success',data:{service:'kt6-task-api'}});}catch(e){next(e);}});
app.use((req,res,next)=>{const e=new Error('Маршрут не найден');e.status=404;next(e);});app.use(errorHandler);
module.exports=app;
